/**
 * Colour schemes for daisyUI, imported from a tweakcn registry (shadcn/ui themes).
 *
 *   vpx plugins/schemes.ts [path/to/tweakcn/registry.json]   (default: ../../tweakcn/registry.json)
 *
 * Writes, both committed (the registry isn't needed to build):
 * - src/styles/schemes.css — each scheme's light and dark palette as daisyUI colour tokens under
 *   `:root[data-scheme="<id>"]`, a separate axis from light/dark (`data-theme`, or the OS when
 *   unset), so every scheme works with System / Dark / Light;
 * - src/styles/schemes.ts — the list the scheme picker shows (names and
 *   swatches).
 *
 * shadcn → daisyUI:
 *   sidebar → base-200 (the app frame and rails; derived from background when they're the same)
 *   background → base-100 (main panel, cards)
 *   border → base-300   foreground → base-content
 *   primary / secondary / accent (+ -foreground → -content)
 *   foreground / background → neutral / neutral-content   destructive → error
 *   radius → field and selector radii, ×1.5 for boxes
 * info / success / warning keep daisyUI's own (tweakcn has none). Fonts are left out: they name
 * web fonts the app doesn't load.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { readableInk } from "./contrast.ts";
import path from "node:path";

type Vars = Record<string, string>;
interface RegistryItem {
  name: string;
  title?: string;
  cssVars: { theme?: Vars; light: Vars; dark: Vars };
}

const TOKENS: [daisy: string, shadcn: string, fallback?: string][] = [
  ["base-100", "background"],
  ["base-200", "sidebar", "background"],
  ["base-300", "border"],
  ["base-content", "foreground"],
  ["primary", "primary"],
  ["primary-content", "primary-foreground"],
  ["secondary", "secondary"],
  ["secondary-content", "secondary-foreground"],
  ["accent", "accent"],
  ["accent-content", "accent-foreground"],
  ["neutral", "foreground"],
  ["neutral-content", "background"],
  ["error", "destructive"],
  ["error-content", "destructive-foreground", "oklch(1 0 0)"],
];

/**
 * A palette as daisyUI tokens. daisyUI's base-200 sits a step darker than base-100 (the frame
 * around the main panel); where a theme's sidebar is just its background, it is derived so.
 */
function palette(vars: Vars, mode: "light" | "dark"): string[] {
  const tokens = new Map<string, string>();
  for (const [daisy, shadcn, fallback] of TOKENS) {
    let value = vars[shadcn] ?? (fallback && (vars[fallback] ?? fallback));
    if (daisy === "base-200" && (!vars.sidebar || vars.sidebar === vars.background))
      value = `color-mix(in oklab, ${vars.background}, black ${mode === "light" ? 4 : 22}%)`;
    if (value) tokens.set(daisy, value);
  }
  // Accessibility: every ink must read on its fill at WCAG AA (4.5:1). Where a scheme's own
  // foreground doesn't, use near-white or near-black instead (tests/contrast.test.ts checks this).
  for (const [ink, fill] of INK_ON) {
    const i = tokens.get(ink);
    const f = tokens.get(fill);
    if (i && f) tokens.set(ink, readableInk(i, f));
  }
  return [...tokens].map(([daisy, value]) => `--color-${daisy}: ${value};`);
}

/** Ink / fill pairs that must contrast (text on buttons, badges, alerts and the page). */
export const INK_ON: [ink: string, fill: string][] = [
  ["base-content", "base-100"],
  ["primary-content", "primary"],
  ["secondary-content", "secondary"],
  ["accent-content", "accent"],
  ["neutral-content", "neutral"],
  ["error-content", "error"],
];

function radii(item: RegistryItem): string[] {
  const r = item.cssVars.theme?.radius ?? item.cssVars.light.radius;
  if (!r) return [];
  return [`--radius-field: ${r};`, `--radius-selector: ${r};`, `--radius-box: calc(${r} * 1.5);`];
}

const block = (selector: string, lines: string[], indent = "") =>
  `${indent}${selector} {\n${lines.map((l) => `${indent}  ${l}`).join("\n")}\n${indent}}`;

export function schemesCss(items: RegistryItem[]): string {
  const parts = items.map((item) => {
    const id = item.name;
    return [
      `/* ${item.title ?? id} */`,
      block(`:root[data-scheme="${id}"]`, [...palette(item.cssVars.light, "light"), ...radii(item)]),
      block(`:root[data-scheme="${id}"][data-theme="dark"]`, palette(item.cssVars.dark, "dark")),
      `@media (prefers-color-scheme: dark) {\n${block(`:root[data-scheme="${id}"]:not([data-theme])`, palette(item.cssVars.dark, "dark"), "  ")}\n}`,
    ].join("\n");
  });
  return `/* GENERATED by plugins/schemes.ts from a tweakcn registry. Do not edit; run \`vpx plugins/schemes.ts\`.
   Colour schemes as daisyUI tokens, chosen with data-scheme on <html> (<ui-appearance
   kind="scheme">); light or dark comes from data-theme, or the OS when it is unset. */
${parts.join("\n\n")}
`;
}

export function schemesModule(items: RegistryItem[]): string {
  const swatch = (v: Vars) => ({ base: v.background, primary: v.primary, secondary: v.secondary, accent: v.accent });
  const list = items.map((i) => ({
    id: i.name,
    label: i.title ?? i.name,
    light: swatch(i.cssVars.light),
    dark: swatch(i.cssVars.dark),
  }));
  return `/* GENERATED by plugins/schemes.ts from a tweakcn registry. Do not edit; run \`vpx plugins/schemes.ts\`. */

/** A colour scheme's swatch colours (for the picker), per mode. */
export interface SchemeSwatch {
  base: string;
  primary: string;
  secondary: string;
  accent: string;
}

export interface Scheme {
  id: string;
  label: string;
  light: SchemeSwatch;
  dark: SchemeSwatch;
}

/** The colour schemes in src/styles/schemes.css. */
export const SCHEMES: Scheme[] = ${JSON.stringify(list, null, 2)};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  const source = path.resolve(process.argv[2] ?? path.join(import.meta.dirname, "../../../tweakcn/registry.json"));
  const items = (JSON.parse(readFileSync(source, "utf8")) as { items: RegistryItem[] }).items.filter(
    (i) => i.cssVars?.light && i.cssVars?.dark,
  );
  const root = path.resolve(import.meta.dirname, "..");
  writeFileSync(path.join(root, "src/styles/schemes.css"), schemesCss(items));
  writeFileSync(path.join(root, "src/styles/schemes.ts"), schemesModule(items));
  console.log(`wrote ${items.length} schemes from ${source}`);
}
