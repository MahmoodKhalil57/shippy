import { Engine, MemoryStore, seedStore, type BackendConfig, type Seeds } from "mock-runner/server";

/**
 * The seed as SQL for D1 (`wrangler d1 execute <db> --file`), made at build time: the seed is
 * written through the same engine the Worker runs (its hooks, defaults and localization, `locale:
 * "all"`), in memory, and what that stored becomes rows of ../migrations' tables. So no request
 * ever seeds (thousands of writes in one Worker request), and the database starts exactly as the
 * browser's backend does.
 *
 * By default only what the database doesn't have is added (`INSERT … ON CONFLICT DO NOTHING`):
 * running it again, or after the seed grows, never overwrites what people changed. `reset`
 * empties the tables first (a demo back to its seed).
 */
export async function seedSql(config: BackendConfig, seeds: Seeds, { reset = false }: { reset?: boolean } = {}) {
  const store = new MemoryStore();
  const engine = new Engine(config, store);
  await seedStore(engine, seeds);
  const q = (v: string) => `'${v.replace(/'/g, "''")}'`;
  const lines: string[] = [
    "-- cf-runner seed (generated by seedSql: don't edit).",
    ...(reset ? ["DELETE FROM docs;", "DELETE FROM globals;", "DELETE FROM files;"] : []),
  ];
  for (const c of config.collections)
    for (const doc of await store.all(c.slug))
      lines.push(
        `INSERT INTO docs (collection, id, data) VALUES (${q(c.slug)}, ${q(doc.id)}, ${q(JSON.stringify(doc))}) ON CONFLICT DO NOTHING;`,
      );
  for (const g of config.globals ?? []) {
    const doc = await store.getGlobal(g.slug);
    if (doc)
      lines.push(
        `INSERT INTO globals (slug, data) VALUES (${q(g.slug)}, ${q(JSON.stringify(doc))}) ON CONFLICT DO NOTHING;`,
      );
  }
  // The seed's bookkeeping (what it loaded), as the browser's backend keeps it.
  for (const key of ["seededIds", "seedHash", "seededAt"]) {
    const value = await store.getMeta(key);
    if (value !== undefined)
      lines.push(
        `INSERT INTO meta (key, value) VALUES (${q(key)}, ${q(JSON.stringify(value))}) ON CONFLICT (key) DO UPDATE SET value = excluded.value;`,
      );
  }
  return `${lines.join("\n")}\n`;
}
