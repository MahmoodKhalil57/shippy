export function inArabic<T>(value: T): T {
  if (typeof value === "string") return (PLATFORM_AR[value] ?? value) as T;
  if (Array.isArray(value)) return value.map(inArabic) as T;
  if (value && typeof value === "object")
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, inArabic(v)])) as T;
  return value;
}
